ROLES = ("top", "wrist", "front", "side")


def usb_binding(adapter, devices):
    if adapter.identity and sum(d.identity == adapter.identity for d in devices) == 1:
        return adapter.identity
    return {"vid": adapter.vid, "pid": adapter.pid, **({"port": adapter.port} if adapter.port else {})}


def calibration_info(robot):
    """Describe the official manual procedure without constructing or opening a device."""
    specs = robot
    if robot["type"] == "rebot_b601":
        specs = {
            "follower": {"type": "rebot_b601_follower", "port": "can0", "id": "follower1",
                         "motor_family": "rs", "can_adapter": "socketcan"},
            "leader": {"type": "rebot_102_leader", "port": robot["leader_port"], "id": "rebot_arm_102_leader"},
        }
    result = []
    for role in ("follower", "leader"):
        spec = specs[role]
        prefix = "robot" if role == "follower" else "teleop"
        kind = spec["type"]
        name = f"so_{role}" if kind.startswith(("so100_", "so101_")) else kind
        path = doctor.calibration_path(role, name, spec["id"], spec.get("calibration_dir"))
        try:
            data = json.loads(path.read_text())
            ready = isinstance(data, dict) and bool(data)
        except (OSError, ValueError):
            ready = False
        result.append({"role": role, "path": str(path), "ready": ready,
                       "command": shlex.join(["lerobot-calibrate", *(f"--{prefix}.{k}={v}" for k, v in spec.items())])})
    return result


def _difference(base, current):
    out = {}
    for key, value in current.items():
        if key not in base:
            out[key] = value
        elif base[key] != value:
            if key != "cameras" and isinstance(value, dict) and isinstance(base[key], dict):
                out[key] = _difference(base[key], value)
            else:
                out[key] = value
    return out


def save_profile(path: Path, profile, overwrite=False):
    defaults = yaml.safe_load(DEFAULT.read_text())
    data = _difference(defaults, profile)
    text = (
        "# Generated by macbot init. Unlisted settings use macbot's built-in defaults.\n"
        "# USB bindings identify the arms. Port paths also serve as calibration references.\n"
        "# Camera names are recording roles; the camera section replaces the built-in cameras.\n"
        + yaml.safe_dump(data, sort_keys=False, allow_unicode=True)
    )
    created = [parent for parent in path.parents if not parent.exists()]
    path.parent.mkdir(parents=True, exist_ok=True)
    for parent in reversed(created):
        give_back(parent)
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, delete=False) as file:
        temporary = Path(file.name)
        try:
            file.write(text)
            file.flush()
            give_back(temporary)
            if overwrite:
                os.replace(temporary, path)
            else:
                os.link(temporary, path)  # atomic create; never clobber another profile
        finally:
            temporary.unlink(missing_ok=True)


def check_profile(cfg):
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        status = doctor.run(cfg)
    return status, out.getvalue()


class Setup:
    def __init__(self, path=None, *, scan=scan_adapters, cameras=discover_cameras, positions=detect_leader,
                 preview=open_preview, calibration=calibration_info, check=check_profile):
        self.path = Path(path) if path is not None else setup_path()
        self.scan, self.discover = scan, cameras
        self.positions, self.preview, self.calibration, self.check = positions, preview, calibration, check
        self.devices, self.cameras, self.notes = [], [], []

    def refresh(self):
        self.devices = self.scan()
        self.cameras, self.notes = self.discover()

    def _adapter(self, index, *, serial=True):
        if type(index) is not int or not 0 <= index < len(self.devices):
            raise ValueError("Select the USB adapter for each arm.")
        dev = self.devices[index]
        if bool(dev.port) != serial:
            raise ValueError("Select a serial adapter for the arm and a PCAN-USB adapter for CAN.")
        return dev

    def _family(self, selection):
        family = selection.get("family")
        if family not in FAMILIES:
            raise ValueError("Confirm the arm model.")
        return family

    def _current(self, devices):
        # Browser selections survive refresh only when sent again against the current inventory.
        current = self.scan()
        if any(dev not in current for dev in devices):
            raise ValueError("USB devices changed. Rescan and confirm the arms again.")

    def move(self, selection):
        family = self._family(selection)
        if family == "rebot_b601":
            raise ValueError("The reBot follower uses CAN. Assign the serial adapter to the leader manually.")
        picks = selection.get("candidates")
        if not isinstance(picks, list) or len(picks) != 2 or picks[0] == picks[1]:
            raise ValueError("Select two different USB serial adapters to sample.")
        devices = [self._adapter(i) for i in picks]
        self._current(devices)
        chosen = self.positions(devices, family)
        return None if chosen is None else picks[chosen]

    def robot_config(self, selection):
        family = self._family(selection)
        leader = self._adapter(selection.get("leader"))
        follower = self._adapter(selection.get("follower"), serial=family != "rebot_b601")
        if leader == follower:
            raise ValueError("The leader and follower must be different devices.")
        self._current([leader, follower])
        follower_role = "can" if family == "rebot_b601" else "follower"
        bindings = {role: usb_binding(d, self.devices) for role, d in [("leader", leader), (follower_role, follower)]}
        if family == "rebot_b601":
            if sum(d.port is None for d in self.devices) != 1:
                raise ValueError("Connect exactly one PCAN-USB adapter for reBot can0.")
            return {"type": family, "leader_port": leader.port, "usb": bindings}
        return {
            "type": "lerobot", "usb": bindings,
            **{role: {"type": f"{family}_{role}", "port": dev.port, "id": calibration_id(bindings[role], role)}
               for role, dev in [("follower", follower), ("leader", leader)]},
        }

    def profile(self, selection):
        robot = self.robot_config(selection)
        assignments = selection.get("cameras", {})
        if not isinstance(assignments, dict) or not assignments:
            raise ValueError("Assign at least one camera role.")
        if any(type(i) is not int or not 0 <= i < len(self.cameras) for i in assignments.values()):
            raise ValueError("Select cameras from the inventory.")
        if set(assignments) - set(ROLES) or len(set(assignments.values())) != len(assignments):
            raise ValueError("Assign each camera and each role only once.")
        cameras = {role: self.cameras[i].config() for role, i in assignments.items()}
        return {"robot": robot, "cameras": cameras, "record": {"fps": min(30, *(c["fps"] for c in cameras.values()))}}

    def save(self, selection, *, overwrite=False):
        profile = self.profile(selection)
        return self.write(profile, overwrite=overwrite)

    def write(self, profile, *, overwrite=False):
        files = self.calibration(profile["robot"])
        missing = [f for f in files if not f["ready"]]
        if missing:
            suffix = "" if shutil.which("lerobot-calibrate") else "\nInstall lerobot[core-scripts]==0.7.0 first."
            raise ValueError("Finish LeRobot calibration first:\n" + "\n".join(f["command"] for f in missing) + suffix)
        save_profile(self.path, profile, overwrite=overwrite)
        return self.check(load(self.path))

    def automatic(self, *, family=None, leader=None, follower=None):
        """Non-interactive setup never samples a motor bus or assigns ambiguous roles."""
        exists = self.path.is_file()
        if exists and not any((family, leader, follower)):
            current = load(self.path)
            robot = current["robot"]
            if not robot.get("usb"):
                raise ValueError("The existing profile has no saved USB roles. Run macbot init to review it.")
            current["robot"] = resolve_robot(robot, lambda: self.devices)
            if any(not f["ready"] for f in self.calibration(current["robot"])):
                raise ValueError("Calibration is missing. Run macbot init for the LeRobot commands.")
            return self.check(current)

        def by_serial(value, *, serial_port=True):
            hits = [i for i, d in enumerate(self.devices) if d.serial == value and bool(d.port) == serial_port]
            if not value or len(hits) != 1:
                raise ValueError("Each supplied USB serial must match one adapter. Run macbot init to select manually.")
            return hits[0]

        if exists:
            raise ValueError("A profile already exists. Run macbot init to review and replace it.")
        serial_ports = [i for i, d in enumerate(self.devices) if d.port]
        can = [i for i, d in enumerate(self.devices) if not d.port]
        if family == "rebot_b601":
            if len(can) != 1 or (not leader and len(serial_ports) != 1) or follower:
                raise ValueError("Expected one PCAN adapter and an unambiguous leader. Run macbot init.")
            family, a, b = "rebot_b601", by_serial(leader) if leader else serial_ports[0], can[0]
        elif family and leader and follower:
            a, b = by_serial(leader), by_serial(follower)
        else:
            raise ValueError("Arm model or roles are ambiguous. Run macbot init or specify --family and both USB serials.")
        cams = [i for i, c in enumerate(self.cameras) if not c.builtin]
        if len(cams) != 1 or not self.cameras[cams[0]].mode:
            raise ValueError("Camera roles are ambiguous or no external camera is ready. Run macbot init.")
        return self.save({"family": family, "leader": a, "follower": b, "cameras": {"top": cams[0]}})

    def remembered(self):
        if not self.path.is_file():
            return {}
        cfg = load(self.path)
        robot = cfg["robot"]
        specs = robot.get("usb", {})
        if not specs:
            return {}
        family = "rebot_b601" if robot["type"] == "rebot_b601" else robot["follower"]["type"].removesuffix("_follower")
        selection = {"family": family, "cameras": {}}
        for role in ("leader", "can" if family == "rebot_b601" else "follower"):
            if role in specs:
                try:
                    dev = resolve_adapter(specs[role], self.devices, serial_port=role != "can")
                    selection["follower" if role == "can" else role] = self.devices.index(dev)
                except ValueError:
                    pass
        for role, spec in cfg["cameras"].items():
            ids = [i for i, c in enumerate(self.cameras)
                   if spec["type"] == c.kind and (spec.get("unique_id") or spec.get("serial")) == c.uid]
            if ids and role in ROLES:
                selection["cameras"][role] = ids[0]
        return selection
