CHOICE = {"family": "so101", "leader": 1, "follower": 0, "cameras": {"top": 0}}
HOST = "127.0.0.1:8765"


@pytest.fixture
def wizard(tmp_path):
    devices = [Adapter(f"/dev/cu.fake{i}", 0x1A86, 0x7523, label, "WCH board") for i, label in enumerate(("F", "L"))]
    cameras = [Camera("uvc", "USB camera", "exact-id", (1280, 720, 30))]
    probe = []
    camera = SimpleNamespace(latest=lambda: (np.zeros((480, 640, 3), dtype=np.uint8), time.time()),
                             close=lambda: probe.append("closed"))

    def positions(devices, family):
        probe.append((devices, family))
        return 1

    obj = Setup(tmp_path / "config.yaml", scan=lambda: devices, cameras=lambda: (cameras, []), positions=positions,
                preview=lambda *_: camera, calibration=lambda _: [], check=lambda _: (0, "fake doctor passed"))
    obj.refresh()
    return obj, probe


def test_generated_config_and_remembered_roles(wizard, monkeypatch):
    from macbot import config

    setup, probe = wizard
    setup.cameras.append(Camera("orbbec", "Gemini", "G1", (640, 480, 15)))
    selection = {**CHOICE, "cameras": {"top": 0, "wrist": 1}}
    assert setup.save(selection) == (0, "fake doctor passed")
    assert not probe
    text = setup.path.read_text()
    assert text.startswith("# Generated by macbot init.")
    assert set(yaml.safe_load(text)) == {"robot", "cameras", "record"}
    cfg = load(setup.path)
    assert cfg["record"]["fps"] == 15 and cfg["teleop"] == load()["teleop"]
    assert cfg["cameras"]["wrist"]["serial"] == "G1"
    assert cfg["cameras"]["top"]["unique_id"] == "exact-id"
    assert setup.remembered() == selection | {"keep_framing": True}
    monkeypatch.setattr(config, "setup_path", lambda: setup.path)
    assert load_cli(None) == cfg
    custom = setup.path.with_name("custom.yaml")
    custom.write_text("task: {name: explicit}\n")
    assert load_cli(custom).task == "explicit"
    with pytest.raises(FileExistsError):
        setup.save(selection)
    with pytest.raises(ValueError, match="only once"):
        setup.save({**selection, "cameras": {"top": 0, "wrist": 0}}, overwrite=True)


def test_noninteractive_stops_when_ambiguous_and_never_reads(wizard, monkeypatch, capsys):
    import macbot.init_wizard as module

    setup, probe = wizard
